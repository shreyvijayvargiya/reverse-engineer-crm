import type { Blueprint } from "../../blueprint/schema.js";
import { CATEGORIES, getTool } from "../../catalog/tools.js";
import { kebab, marker } from "./names.js";

function toolsOf(bp: Blueprint) {
  return bp.tools.map((id) => getTool(id)).filter((t): t is NonNullable<typeof t> => Boolean(t));
}

export function renderReadme(bp: Blueprint): string {
  const modules = bp.modules.map((m) => `- **${m.label}**: ${m.description} (\`/${kebab(m.id)}\`)`).join("\n");
  return `${marker.md}# ${bp.name}

${bp.description}

Generated by [Reverse Engineer CRM](https://github.com/shreyvijayvargiya/reverse-engineer-crm). This is a frontend-only React app (Vite, TypeScript, Tailwind, lucide-react). It runs on demo data in your browser, and every third-party integration is a typed stub you can wire to a backend later.

## Run it

\`\`\`bash
npm install
npm run dev
\`\`\`

## What is in it

${modules}

Integrations (mock until you wire them): ${toolsOf(bp).map((t) => t.name).join(", ") || "none"}. See [INTEGRATIONS.md](INTEGRATIONS.md).

## What is real and what is mocked

| Part | State |
| --- | --- |
| UI, tables, kanban, forms, search, CSV export | Real |
| Records | Real, stored in this browser's localStorage |
| Sending messages, payments, scraping, calendar, etc. | **Mocked** by \`src/services/*\` until you set \`VITE_API_BASE_URL\` and build the backend routes |

## Change the CRM

Edit \`blueprint.json\` (or run \`rcrm add <module-or-tool>\`), then \`rcrm regenerate\`. Files carrying the \`@rcrm-generated\` marker are refreshed; delete the marker line from any file you want to hand-edit and it will be left alone.

## Hand it to a coding agent

[AGENTS.md](AGENTS.md) has the architecture and a ready prompt for each integration.
`;
}

export function renderIntegrations(bp: Blueprint): string {
  const tools = toolsOf(bp);
  if (tools.length === 0) {
    return `${marker.md}# Integrations

This CRM uses no third-party tools. Add some with \`rcrm add <tool-id>\` (see \`rcrm tools\`).
`;
  }
  const rows = tools
    .map((t) => {
      const c = CATEGORIES[t.category];
      const inUse = bp.primaryTools[t.category] === t.id ? "in use" : "stub only";
      return `| ${t.name} | ${t.category} (${inUse}) | \`${c.method}\` | ${t.envVars.map((v) => `\`${v}\``).join(", ")} | [docs](${t.docsUrl}) |`;
    })
    .join("\n");
  const detail = tools
    .map((t) => {
      const c = CATEGORIES[t.category];
      return `### ${t.name}

- Stub: \`src/services/${t.id}.ts\`
- Backend route to implement: \`POST /${t.id}/${c.method}\` (request/response shapes in \`openapi.yaml\`)
- Vendor call: \`${t.http}\`
- Auth: ${t.auth}
${t.note ? `- Note: ${t.note}\n` : ""}`;
    })
    .join("\n");
  return `${marker.md}# Integrations

The browser never talks to a vendor directly. Each tool has a stub in \`src/services/\` that either returns mock data or, when \`VITE_API_BASE_URL\` is set, POSTs JSON to \`<base>/<tool>/<method>\`. You implement those routes on a server you control, which holds the vendor credentials.

Vendor endpoints below are scaffolding hints from the vendors' public docs at generation time. Vendors version their APIs: confirm each against its docs before relying on it.

| Tool | Category | Method | Backend env vars | Docs |
| --- | --- | --- | --- | --- |
${rows}

## Going live checklist

1. Build a small backend (any language) exposing the routes in \`openapi.yaml\`.
2. Put vendor credentials in the backend's environment (see \`.env.example\`), never in \`VITE_\` variables.
3. Set \`VITE_API_BASE_URL\` in \`.env.local\` and restart \`npm run dev\`.
4. Replace localStorage with your database (see AGENTS.md, "Data layer").
5. Messaging: only contact people who opted in, and follow each provider's policy (WhatsApp templates, SMS/DLT rules, email unsubscribe).
6. Scraping: only collect data you are permitted to, and respect each site's terms and robots.txt.

## Details

${detail}`;
}

export function renderAgents(bp: Blueprint): string {
  const tools = toolsOf(bp);
  const entities = bp.modules.flatMap((m) => m.entities);
  const dataModel = entities
    .map((e) => `- \`${e.key}\` (${e.plural}): ${e.fields.map((f) => `${f.key}:${f.type}`).join(", ")}`)
    .join("\n");
  const prompts = tools
    .map((t) => {
      const c = CATEGORIES[t.category];
      return `- **${t.name}**: "Implement \`POST /${t.id}/${c.method}\` on the backend. Request/response shapes are in \`openapi.yaml\` under \`${c.input}\`/\`${c.output}\`. Call \`${t.http}\` using env vars ${t.envVars.join(", ")}. Check ${t.docsUrl} for the current request format first. Then set \`VITE_API_BASE_URL\` and verify the UI action that uses it."`;
    })
    .join("\n");
  return `${marker.md}# AGENTS.md

Guidance for AI coding agents working in this repository.

## What this is
${bp.name}: ${bp.description}
Frontend-only React app (Vite + TypeScript + Tailwind + lucide-react). Generated from \`blueprint.json\` by Reverse Engineer CRM.

## Commands
- \`npm install\`, \`npm run dev\`, \`npm run build\` (typechecks, then builds), \`npm run typecheck\`

## Architecture
- \`blueprint.json\`: source of truth for modules, entities, fields, actions, tools. Regenerate with \`rcrm regenerate\`.
- \`src/generated/\`: blueprint and seed data baked for the app. Do not hand-edit; regenerate.
- \`src/lib/store.ts\`: in-memory store mirrored to localStorage; \`persistence\` is the swap point for a real database.
- \`src/lib/actions.ts\`: behaviour behind action ids (send broadcast, create payment link, run scraper...).
- \`src/services/\`: one typed stub per tool. \`_runtime.ts\` decides mock vs backend call.
- \`src/components/EntityView.tsx\`: generic table, kanban, form and action UI for every entity.
- \`src/pages/modules/*.tsx\`: one page per module; edit freely after removing the \`@rcrm-generated\` line.

## Conventions
- Never put API keys or tokens in the frontend or in \`VITE_\` variables. Vendor calls belong on a backend.
- Keep the service interface per category stable (\`src/services/types.ts\`); change the stub's internals, not the UI.
- Messaging actions only target contacts with \`marketingOptIn\` true when that field exists. Keep that gate.
- New entity or field: edit \`blueprint.json\`, run \`rcrm regenerate\`, then \`npm run build\`.

## Data model
${dataModel}

## Data layer (${bp.dataLayer})
Records currently live in localStorage. To use a database, implement \`load\`/\`save\`/\`clear\` of \`persistence\` in \`src/lib/store.ts\` against it (or call your API from \`store\` methods), keeping the same shapes.${bp.dataLayer === "supabase" ? " `supabase/schema.sql` has matching tables with row level security enabled and no policies; add policies before use." : ""}

## Wiring each integration (prompts you can reuse)
${prompts || "No third-party tools in this blueprint."}

## Definition of done for a change
- \`npm run build\` passes.
- The UI action that uses the changed service works in mock mode and, if a backend exists, in live mode.
- No secrets in the diff.
`;
}
